export function xpProgress(xp) {
  const l = levelOf(xp);
  if (l >= MAXL) return { l, frac: 1, need: 0 };
  const a = lvlXP(l),
    b = lvlXP(l + 1);
  return { l, frac: (xp - a) / (b - a), need: b - xp };
}
