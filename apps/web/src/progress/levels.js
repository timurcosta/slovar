export const MAXL = 50;
const lvlXP = (n) => 50 * n * (n - 1) + n * n * n; // xp needed to reach level n (v2: late levels slower)
export const levelOf = (xp) => {
  let l = 1;
  while (l < MAXL && xp >= lvlXP(l + 1)) l++;
  return l;
};
