export function towerBoss(floor) {
  const base = pick(TOWER_BOSSES),
    k = (Math.random() * TOWER_PREFIX.length) | 0,
    [short, f] = TOWER_NAME[base.pal];
  const pool = shuffle([
    "regen",
    "armor",
    "haste",
    "double",
    "swap",
    "fog",
    "flip",
    "ink",
    "freeze",
    "steal",
    "tiny",
    "scramble",
    "stamp",
    "dark",
    "web",
    "rush",
    "vampire",
    "glitch",
    "cloud",
    "lens",
    "minions",
    "cups",
    "bubble",
    "charge",
  ]);
  const ab = [pool[0]];
  if (floor >= 6) ab.push(pool[1]);
  if (floor >= 15) ab.push(pool[2]);
  if (floor >= 3) ab.push("enrage");
  const name = `${TOWER_PREFIX[k][f ? 1 : 0]} ${short}`;
  return {
    name,
    spr: base.spr,
    pal: base.pal,
    f,
    ab,
    pool: "tower",
    filter: TOWER_FILTER[k],
    hp: Math.round(110 + floor * 22 + floor * floor * 0.35),
    time: Math.max(4.5, 12 - floor * 0.3),
    taunts: base.taunts,
    floor,
    // страж каждого 10-го этажа превращается (секрет: в интро об этом ни слова)
    forms:
      floor % 10 === 0
        ? [{ at: 0.4, name: `${f ? "Великая" : "Великий"} ${short}`, ab: pool[3], say: "Страж башни не сдаётся!" }]
        : undefined,
  };
}
