// глаза 5×5: янтарные, кошачий зрачок, хитро прикрытое веко; «.» — шерсть; правый глаз — зеркало левого
const EYES = {
  open: [".jjj.", "JJJjj", "JEKJJ", "JJKJJ", ".LKL."],
  blink: [".....", ".....", ".....", "jjjjj", "....."],
  happy: [".....", ".....", ".JJJ.", "J...J", "....."],
};
const EYE_Y = 8,
  EYE_L = 11,
  EYE_R = 23;

/** Кот: frame — 0/1, mood — open | blink | happy. */
export function merchantSprite(frame = 0, mood = "open") {
  const g = CAT[frame]
    .trim()
    .split("\n")
    .map((r) => [...r]);
  EYES[mood].forEach((line, y) =>
    [...line].forEach((c, i) => {
      g[EYE_Y + y][EYE_L + i] = g[EYE_Y + y][EYE_R - i] = c === "." ? "K" : c;
    }),
  );
  return g.map((r) => r.join("")).join("\n");
}
/** Прилавок: пиала с лапкой и чак-чак, frame — 0/1 (пар). */
export const merchantTable = (frame = 0) => TABLE[frame].trim();
/** Кот и прилавок одной картинкой (для предпросмотра). */
export function merchantScene(frame = 0, mood = "open") {
  const g = merchantSprite(frame, mood)
    .split("\n")
    .map((r) => [...r]);
  merchantTable(frame)
    .split("\n")
    .forEach((r, y) => [...r].forEach((c, x) => c !== "." && (g[y][x] = c)));
  return g.map((r) => r.join("")).join("\n");
}

