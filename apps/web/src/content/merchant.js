// глаза-дужки «^ ^», когда Котофей доволен: [x, y, цвет] поверх сонных глаз
const EYES = [10, 11, 12, 13, 17, 18, 19, 20];
const HAPPY = [
  ...EYES.flatMap((x) => [15, 16, 17].map((y) => [x, y, "K"])),
  ...[11, 12, 18, 19].map((x) => [x, 15, "Y"]),
  ...[10, 13, 17, 20].map((x) => [x, 16, "Y"]),
];

/** Кадр Котофея: frame — 0/1, happy — глаза дужками. */
export function merchantSprite(frame = 0, happy = false) {
  const rows = FRAMES[frame].trim().split("\n");
  if (!happy) return rows.join("\n");
  const g = rows.map((r) => [...r]);
  for (const [x, y, c] of HAPPY) g[y][x] = c;
  return g.map((r) => r.join("")).join("\n");
}

